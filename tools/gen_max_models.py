"""Generates src/matele/max/models.py from schema/max/schema.json (the
official MAX Bot API OpenAPI schema). Run from the repository root:

	python tools/gen_max_models.py

Rules:
  • object schemas -> @dataclass(kw_only=True) subclasses of Model;
	`allOf: [$ref Base, {...}]` -> subclass of Base;
  • a schema with a `discriminator` is the base of a polymorphic family:
	its subclasses get the tag as the default of the tag field, and the
	base gets __tag__ / __subtypes__ so decoding picks the right class;
  • string enums -> Literal aliases; integer/string id aliases -> int/str;
  • a field is required (no default) only if it is required and not
	nullable; everything else is `T | None = None`;
  • descriptions become docstrings.
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema" / "max" / "schema.json"
OUT = ROOT / "src" / "matele" / "max" / "models.py"

PRIMITIVES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}


def ref_name(ref: str) -> str:
	return ref.rsplit("/", 1)[-1]


class Generator:
	def __init__(self, schema: dict):
		self.schema = schema
		self.schemas: dict[str, dict] = schema["components"]["schemas"]
		self.version = schema["info"]["version"]
		# tag value of each subclass, from its base's discriminator mapping
		self.tag_of: dict[str, tuple[str, str]] = {}  # class -> (tag field, tag value)
		self.families: dict[str, tuple[str, dict[str, str]]] = {}  # base -> (tag field, value -> class)
		for name, s in self.schemas.items():
			disc = s.get("discriminator")
			if disc:
				mapping = {value: ref_name(ref) for value, ref in disc.get("mapping", {}).items()}
				self.families[name] = (disc["propertyName"], mapping)
				for value, cls in mapping.items():
					self.tag_of[cls] = (disc["propertyName"], value)

	# ------------------------------------------------------------ kinds
	def is_enum(self, name: str) -> bool:
		return "enum" in self.schemas[name]

	def is_scalar(self, name: str) -> bool:
		s = self.schemas[name]
		return s.get("type") in PRIMITIVES and "enum" not in s and "properties" not in s

	def is_object(self, name: str) -> bool:
		return not self.is_enum(name) and not self.is_scalar(name)

	def base_of(self, name: str) -> str | None:
		for part in self.schemas[name].get("allOf", []):
			if "$ref" in part and self.is_object(ref_name(part["$ref"])):
				return ref_name(part["$ref"])
		return None

	def own_properties(self, name: str) -> tuple[dict[str, dict], set[str]]:
		s = self.schemas[name]
		props = dict(s.get("properties", {}))
		required = set(s.get("required", []))
		for part in s.get("allOf", []):
			if "$ref" not in part:
				props.update(part.get("properties", {}))
				required |= set(part.get("required", []))
		return props, required

	# ------------------------------------------------------------ types
	def type_of(self, p: dict) -> str:
		if "$ref" in p:
			return self.named(ref_name(p["$ref"]))
		refs = [a for a in p.get("allOf", []) if "$ref" in a]
		if len(refs) == 1:
			return self.named(ref_name(refs[0]["$ref"]))
		t = p.get("type")
		if t == "string" and "enum" in p:
			return "Literal[" + ", ".join(json.dumps(v) for v in p["enum"]) + "]"
		if t in PRIMITIVES:
			return PRIMITIVES[t]
		if t == "array" or (t is None and "items" in p):  # the schema sometimes omits `type: array`
			return f"list[{self.type_of(p['items'])}]"
		if t == "object" and isinstance(p.get("additionalProperties"), dict):
			return f"dict[str, {self.type_of(p['additionalProperties'])}]"
		if t == "object":
			return "dict[str, Any]"
		return "Any"

	def named(self, name: str) -> str:
		if self.is_scalar(name):
			return PRIMITIVES[self.schemas[name]["type"]]
		return name

	# ------------------------------------------------------------ output
	def order(self) -> list[str]:
		"""Object schemas, every base before its subclasses, otherwise in schema order."""
		done: list[str] = []

		def visit(name: str) -> None:
			if name in done:
				return
			base = self.base_of(name)
			if base:
				visit(base)
			done.append(name)

		for name in self.schemas:
			if self.is_object(name):
				visit(name)
		return done

	def render(self) -> str:
		out: list[str] = [
			f'"""MAX Bot API models (API version {self.version}).',
			"",
			"GENERATED by tools/gen_max_models.py from schema/max/schema.json: do not edit by hand.",
			"The schema is (c) MAX, Apache License 2.0; see schema/max/README.md.",
			'"""',
			"",
			"# ruff: noqa: E501",
			"from __future__ import annotations",
			"",
			"from dataclasses import dataclass",
			"from typing import Any, Literal",
			"",
			"from matele.max._model import Model, wire, wire_optional",
			"",
			f'API_VERSION = "{self.version}"',
			"",
		]
		names: list[str] = ["API_VERSION"]
		for name, s in self.schemas.items():
			if self.is_enum(name):
				out.append(f"{name} = Literal[" + ", ".join(json.dumps(v) for v in s["enum"]) + "]")
				doc = docstring(s.get("description"))
				if doc:
					out.append(doc)
				out.append("")
				names.append(name)
		out.append("")
		for name in self.order():
			out.extend(self.render_class(name))
			names.append(name)
		out.append("# Polymorphic families: tag value -> class.")
		for base, (tag, mapping) in self.families.items():
			out.append(f'{base}.__tag__ = "{tag}"')
			items = ", ".join(f'"{value}": {cls}' for value, cls in mapping.items())
			out.append(f"{base}.__subtypes__ = {{{items}}}")
		out.append("")
		out.append("__all__ = [")
		out.extend(f'\t"{n}",' for n in sorted(names))
		out.append("]")
		text = "\n".join(out) + "\n"
		body = text.split('API_VERSION = "', 1)[1]
		helpers = ", ".join(h for h in ("Model", "wire", "wire_optional") if h == "Model" or f"{h}(" in body)
		# only annotation lines count: docstrings say "Any external image URL"
		annotations = "\n".join(re.findall(r"^(?:\t\w+: .*|\w+ = Literal\[.*)$", body, re.M))
		typing_names = ", ".join(n for n in ("Any", "Literal") if re.search(rf"\b{n}\b", annotations))
		text = text.replace("from typing import Any, Literal", f"from typing import {typing_names}")
		return text.replace(
			"from matele.max._model import Model, wire, wire_optional", f"from matele.max._model import {helpers}"
		)

	def render_class(self, name: str) -> list[str]:
		s = self.schemas[name]
		base = self.base_of(name) or "Model"
		props, required = self.own_properties(name)
		lines = ["@dataclass(kw_only=True)", f"class {name}({base}):"]
		doc = docstring(s.get("description"), indent="\t")
		if doc:
			lines.append(doc)
		body: list[str] = []
		tag = self.tag_of.get(name)
		if tag is not None and tag[0] not in props:
			body.append(f'\t{tag[0]}: str = "{tag[1]}"')
		for prop, p in props.items():
			py = prop + "_" if keyword.iskeyword(prop) or not prop.isidentifier() else prop
			t = self.type_of(p)
			if tag is not None and prop == tag[0]:
				body.append(f'\t{py}: str = "{tag[1]}"')
			elif prop in required and not p.get("nullable"):
				default = f" = wire({json.dumps(prop)})" if py != prop else ""
				body.append(f"\t{py}: {t}{default}")
			else:
				default = f"wire_optional({json.dumps(prop)})" if py != prop else "None"
				body.append(f"\t{py}: {t} | None = {default}")
			field_doc = docstring(p.get("description"), indent="\t")
			if field_doc:
				body.append(field_doc)
		if not body and not doc:
			body.append("\tpass")
		lines.extend(body)
		lines.extend(["", ""])
		return lines


def docstring(text: str | None, indent: str = "") -> str:
	if not text:
		return ""
	text = re.sub(r"\s+\n", "\n", text.strip()).replace("\\", "\\\\").replace('"""', "'''")
	if text.endswith('"'):
		text += " "
	lines = text.split("\n")
	if len(lines) == 1:
		return f'{indent}"""{text}"""'
	return "\n".join(
		[f'{indent}"""{lines[0]}', *[f"{indent}{line}" if line else "" for line in lines[1:]], f'{indent}"""']
	)


def main() -> None:
	schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
	OUT.write_text(Generator(schema).render(), encoding="utf-8", newline="\n")
	subprocess.run([sys.executable, "-m", "ruff", "format", str(OUT)], check=True)
	print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
	main()
